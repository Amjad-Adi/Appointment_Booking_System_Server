export async function create(invitation: CreateInvitation):Promise<Invitation> {
    return (await pool.query(
        `INSERT INTO ${TABLE_NAME}(${COLUMN_SENDER_ID},${COLUMN_RECIPIENT_EMAIL},${COLUMN_EXPIRES_AT_UTC})
                    VALUES ($1,$2,$3)
                    RETURNING ${COLUMN_UUID},${COLUMN_CREATED_AT_UTC},${COLUMN_EXPIRES_AT_UTC},${COLUMN_INVITATION_STATUS}`,
        [invitation.senderId, invitation.email,invitation.expiresAtUTC])).rows[0];
}

