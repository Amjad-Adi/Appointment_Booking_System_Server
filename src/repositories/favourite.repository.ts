const CATEGORIES_SUBQUERY = `COALESCE((
    SELECT jsonb_agg(
        jsonb_build_object(
            '${SERVICE_CATEGORY_COLUMN_UUID}', ${SERVICE_CATEGORY_ALIAS}.${SERVICE_CATEGORY_COLUMN_UUID},
            '${SERVICE_CATEGORY_COLUMN_NAME}', ${SERVICE_CATEGORY_ALIAS}.${SERVICE_CATEGORY_COLUMN_NAME},
            '${SERVICE_CATEGORY_COLUMN_DESCRIPTION}', ${SERVICE_CATEGORY_ALIAS}.${SERVICE_CATEGORY_COLUMN_DESCRIPTION},
            '${SERVICE_CATEGORY_ALIAS_COLUMN_PICTURE_PATH}', ${SERVICE_CATEGORY_ALIAS}.${SERVICE_CATEGORY_COLUMN_PICTURE_PATH},
            '${SERVICE_CATEGORY_ALIAS_COLUMN_CREATED_AT_UTC}', ${SERVICE_CATEGORY_ALIAS}.${SERVICE_CATEGORY_COLUMN_CREATED_AT_UTC},
            '${SERVICE_CATEGORY_ALIAS_COLUMN_UPDATED_AT_UTC}', ${SERVICE_CATEGORY_ALIAS}.${SERVICE_CATEGORY_COLUMN_UPDATED_AT_UTC},
            '${SERVICE_CATEGORY_COLUMN_STATUS}', ${SERVICE_CATEGORY_ALIAS}.${SERVICE_CATEGORY_COLUMN_STATUS}
        )
        ORDER BY ${SERVICE_CATEGORY_ALIAS}.${SERVICE_CATEGORY_COLUMN_NAME}
    )
    FROM ${SERVICE_JUNCTION_CATEGORY_TABLE_NAME} ${SERVICE_JUNCTION_CATEGORY_ALIAS}
    INNER JOIN ${SERVICE_CATEGORY_TABLE_NAME} ${SERVICE_CATEGORY_ALIAS}
        ON ${SERVICE_JUNCTION_CATEGORY_ALIAS}.${COLUMN_SERVICE_CATEGORY_ID} = ${SERVICE_CATEGORY_ALIAS}.${SERVICE_CATEGORY_COLUMN_ID}
    WHERE ${SERVICE_JUNCTION_CATEGORY_ALIAS}.${SERVICE_JUNCTION_COLUMN_SERVICE_ID} = ${SERVICE_ALIAS}.${COLUMN_ID}
), '[]'::jsonb)`;

const SERVICE_COLUMNS = `${SERVICE_ALIAS}.${COLUMN_UUID},${SERVICE_ALIAS}.${COLUMN_NAME},${SERVICE_ALIAS}.${COLUMN_DESCRIPTION},${SERVICE_ALIAS}.${COLUMN_PRICE}::float8,${SERVICE_ALIAS}.${COLUMN_DURATION_IN_MINUTES} AS ${ALIAS_COLUMN_DURATION_IN_MINUTES},${ORGANIZATION_ALIAS}.${ORGANIZATION_COLUMN_UUID} AS ${ALIAS_COLUMN_ORGANIZATION_UUID},${ORGANIZATION_ALIAS}.${ORGANIZATION_COLUMN_NAME} AS ${ORGANIZATION_ALIAS_COLUMN_NAME},${ORGANIZATION_ALIAS}.${COLUMN_PROFILE_PICTURE_PATH} AS ${ORGANIZATION_ALIAS_COLUMN_PROFILE_PICTURE_PATH},${SERVICE_ALIAS}.${COLUMN_PICTURE_PATH} AS ${ALIAS_COLUMN_PICTURE_PATH},${SERVICE_ALIAS}.${COLUMN_CREATED_AT_UTC} AS ${ALIAS_COLUMN_CREATED_AT_UTC},${SERVICE_ALIAS}.${COLUMN_UPDATED_AT_UTC} AS ${ALIAS_COLUMN_UPDATED_AT_UTC},${SERVICE_ALIAS}.${COLUMN_STATUS}`;

const RATING_COLUMNS = `COALESCE((
        SELECT ROUND(AVG(review.rating)::numeric, 2)::float8
        FROM reviews review
        INNER JOIN appointments appointment ON appointment.id = review.appointment_id
        WHERE appointment.service_id = ${SERVICE_ALIAS}.${COLUMN_ID}
    ), 0) AS "averageRating",
    (
        SELECT COUNT(*)
        FROM reviews review
        INNER JOIN appointments appointment ON appointment.id = review.appointment_id
        WHERE appointment.service_id = ${SERVICE_ALIAS}.${COLUMN_ID}
    ) AS "reviewCount"`;

const FROM_CLAUSE = `FROM ${FAVOURITE_TABLE_NAME} ${FAVOURITE_ALIAS}
    INNER JOIN ${USER_TABLE_NAME} ${USER_ALIAS}
        ON ${USER_ALIAS}.${USER_COLUMN_ID} = ${FAVOURITE_ALIAS}.${COLUMN_USER_ID}
    INNER JOIN ${SERVICE_TABLE_NAME} ${SERVICE_ALIAS}
        ON ${SERVICE_ALIAS}.${COLUMN_ID} = ${FAVOURITE_ALIAS}.${COLUMN_SERVICE_ID}
    INNER JOIN ${ORGANIZATION_TABLE_NAME} ${ORGANIZATION_ALIAS}
        ON ${ORGANIZATION_ALIAS}.${ORGANIZATION_COLUMN_ID} = ${SERVICE_ALIAS}.${COLUMN_ORGANIZATION_ID}`;

const FILTER_CLAUSE = `WHERE ${USER_ALIAS}.${USER_COLUMN_UUID} = $1
    AND ($2::TEXT IS NULL OR ${SERVICE_ALIAS}.${COLUMN_NAME} ILIKE $2 OR ${ORGANIZATION_ALIAS}.${ORGANIZATION_COLUMN_NAME} ILIKE $2)
    AND ($3::UUID IS NULL OR EXISTS (
        SELECT 1
        FROM ${SERVICE_JUNCTION_CATEGORY_TABLE_NAME} ${SERVICE_JUNCTION_CATEGORY_ALIAS}
        INNER JOIN ${SERVICE_CATEGORY_TABLE_NAME} ${SERVICE_CATEGORY_ALIAS}
            ON ${SERVICE_JUNCTION_CATEGORY_ALIAS}.${COLUMN_SERVICE_CATEGORY_ID} = ${SERVICE_CATEGORY_ALIAS}.${SERVICE_CATEGORY_COLUMN_ID}
        WHERE ${SERVICE_JUNCTION_CATEGORY_ALIAS}.${SERVICE_JUNCTION_COLUMN_SERVICE_ID} = ${SERVICE_ALIAS}.${COLUMN_ID}
        AND ${SERVICE_CATEGORY_ALIAS}.${SERVICE_CATEGORY_COLUMN_UUID} = $3
    ))
    AND ${SERVICE_ALIAS}.${COLUMN_STATUS} = 'ACTIVE'`;

export async function findAll(query: QueryFavourite): Promise<FavouriteServiceResponse[]> {
    const search = query.search ? `%${query.search}%` : null;
    const sortColumnsDefinition = {
        [SORT_BY_NAME]: `${SERVICE_ALIAS}.${COLUMN_NAME}`,
        [SORT_BY_PRICE]: `${SERVICE_ALIAS}.${COLUMN_PRICE}`,
        [SORT_BY_FAVOURITED_AT_UTC]: `${FAVOURITE_ALIAS}.${FAVOURITE_COLUMN_CREATED_AT_UTC}`,
    };
    const sortColumn = sortColumnsDefinition[query.sortBy ?? SORT_BY_FAVOURITED_AT_UTC];
    const sortOrder = query.order?.toUpperCase() ?? Order.DESC;
    const serviceCategoryUuid = query.filter?.serviceCategoryUuid ?? null;

    return (await pool.query(
        `SELECT ${SERVICE_COLUMNS},${FAVOURITE_ALIAS}.${FAVOURITE_COLUMN_CREATED_AT_UTC} AS ${ALIAS_COLUMN_FAVOURITED_AT_UTC},TRUE AS "isFavourite",${RATING_COLUMNS},${CATEGORIES_SUBQUERY} AS ${ALIAS_CATEGORIES}
         ${FROM_CLAUSE}
         ${FILTER_CLAUSE}
         ORDER BY ${sortColumn} ${sortOrder},${SERVICE_ALIAS}.${COLUMN_UUID}
         LIMIT $4
         OFFSET $5`,
        [query.userUuid, search, serviceCategoryUuid, query.limit, query.offset],
    )).rows;
}

export async function countAll(query: QueryFavourite): Promise<number> {
    const search = query.search ? `%${query.search}%` : null;
    const serviceCategoryUuid = query.filter?.serviceCategoryUuid ?? null;

    return Number((await pool.query(
        `SELECT COUNT(*) AS ${ALIAS_TOTAL_NUMBER_OF_FAVOURITES}
         ${FROM_CLAUSE}
         ${FILTER_CLAUSE}`,
        [query.userUuid, search, serviceCategoryUuid],
    )).rows[0].totalNumberOfFavourites);
}

export async function create(userUuid: string, serviceUuid: string): Promise<boolean> {
    const result = await pool.query(
        `INSERT INTO ${FAVOURITE_TABLE_NAME} (${COLUMN_USER_ID}, ${COLUMN_SERVICE_ID})
         SELECT ${USER_ALIAS}.${USER_COLUMN_ID}, ${SERVICE_ALIAS}.${COLUMN_ID}
         FROM ${USER_TABLE_NAME} ${USER_ALIAS}
         INNER JOIN ${SERVICE_TABLE_NAME} ${SERVICE_ALIAS} ON ${SERVICE_ALIAS}.${COLUMN_UUID} = $2
         WHERE ${USER_ALIAS}.${USER_COLUMN_UUID} = $1
         ON CONFLICT (${COLUMN_USER_ID}, ${COLUMN_SERVICE_ID}) DO NOTHING
         RETURNING ${COLUMN_CREATED_AT_UTC}`,
        [userUuid, serviceUuid],
    );

    return result.rowCount !== 0;
}

export async function remove(userUuid: string, serviceUuid: string): Promise<boolean> {
    const result = await pool.query(
        `DELETE FROM ${FAVOURITE_TABLE_NAME} ${FAVOURITE_ALIAS}
         USING ${USER_TABLE_NAME} ${USER_ALIAS}, ${SERVICE_TABLE_NAME} ${SERVICE_ALIAS}
         WHERE ${FAVOURITE_ALIAS}.${COLUMN_USER_ID} = ${USER_ALIAS}.${USER_COLUMN_ID}
           AND ${FAVOURITE_ALIAS}.${COLUMN_SERVICE_ID} = ${SERVICE_ALIAS}.${COLUMN_ID}
           AND ${USER_ALIAS}.${USER_COLUMN_UUID} = $1
           AND ${SERVICE_ALIAS}.${COLUMN_UUID} = $2`,
        [userUuid, serviceUuid],
    );

    return result.rowCount !== 0;
}

export async function serviceExists(serviceUuid: string): Promise<boolean> {
    return (await pool.query(
        `SELECT 1 FROM ${SERVICE_TABLE_NAME} WHERE ${COLUMN_UUID} = $1 AND ${COLUMN_STATUS} = 'ACTIVE'`,
        [serviceUuid],
    )).rowCount !== 0;
}
